"""Package capital-region-map.html as an upload-ready static site in ../site/ (plus ../site.zip).

Adds what a hosted copy benefits from but the single local file doesn't need:
  index.html          the map, with home-screen manifest + icon links added to <head>
  manifest.webmanifest  name/colours/icons for "Add to Home screen" on Android
  icon-192.png, icon-512.png, apple-touch-icon.png
  _headers            security headers, including a Content-Security-Policy that allows only this site's own
                      inline scripts (by hash, recomputed on every build), Leaflet from cdnjs and the tile servers

Usage (from the project root):  python build/make_site.py
Icons are drawn with Pillow if it is installed; otherwise the copies in build/icons/ are used (Cloudflare's
build machines have no Pillow). After changing draw_icon(), copy the new site/*.png into build/icons/.
"""
import base64, hashlib, json, re, shutil, sys, zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "capital-region-map.html"
SITE = ROOT / "site"
NAVY, GOLD = "#2D3E52", "#D5A754"

HEAD_EXTRA = """<link rel="manifest" href="manifest.webmanifest">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Iceland">
"""

MANIFEST = {
    "name": "Iceland for Beginners",
    "short_name": "Iceland",                      # home-screen label: the full name would be cut off
    "description": "Neighbourhoods, towns, sights and postal codes all over Iceland, with Icelandic pronunciation.",
    "start_url": "./",
    "scope": "./",
    "display": "standalone",
    "background_color": NAVY,
    "theme_color": NAVY,
    "icons": [
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
        {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
        {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
    ],
}

HEADERS = """# Content-Security-Policy below is generated by build/make_site.py. If you turn on a Cloudflare feature that
# adds a script to the page (Web Analytics, Rocket Loader, Email Address Obfuscation, Zaraz...), add its source
# to csp_for() in make_site.py and rebuild, or the policy will block it.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: geolocation=(self), camera=(), microphone=(self), payment=(), usb=()
  X-Frame-Options: SAMEORIGIN
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Cross-Origin-Opener-Policy: same-origin
  Content-Security-Policy: {csp}

# Long caching: clips never change under the same id (make_audio.py never reuses one), and streets.js /
# addresses.js carry their content's hash in the name. index.html keeps Cloudflare's default (revalidate).
/_assets/*
  Cache-Control: public, max-age=31536000, immutable
/manifest.webmanifest
  Cache-Control: public, max-age=86400
/icon-*
  Cache-Control: public, max-age=86400
/apple-touch-icon.png
  Cache-Control: public, max-age=86400
"""
LEAFLET = "https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/"   # only Leaflet, not all of cdnjs
TILES = ("https://tile.openstreetmap.org https://tile.openstreetmap.de https://*.tile.openstreetmap.fr "
         "https://server.arcgisonline.com")


def csp_for(html):
    """Only the page's own inline scripts may run (each pinned by its SHA-256), plus Leaflet from cdnjs
    (only its own folder there, and pinned by SRI in the page). The page makes no fetch/XHR calls (connect-src 'none'). Map tiles from the listed servers; audio and addresses from this site.

    NOTE: Cloudflare features that inject scripts are blocked by this policy until added here:
      Web Analytics  -> script-src https://static.cloudflareinsights.com; connect-src https://cloudflareinsights.com
      Rocket Loader / Email Address Obfuscation / Zaraz -> their /cdn-cgi/ scripts are same-origin ('self'), but
        Rocket Loader and Email Obfuscation also rewrite inline scripts, which breaks the hashes: keep them off.
    A new map provider needs its tile host added to TILES."""
    hashes = ["'sha256-" + base64.b64encode(hashlib.sha256(m.group(1).encode("utf-8")).digest()).decode() + "'"
              for m in re.finditer(r"<script>(.*?)</script>", html, re.S)]
    return "; ".join([
        "default-src 'self'",
        f"script-src 'self' {LEAFLET} " + " ".join(hashes),
        f"style-src 'self' 'unsafe-inline' {LEAFLET}",
        f"img-src 'self' data: {LEAFLET} {TILES}",
        "connect-src 'none'", "media-src 'self'", "manifest-src 'self'", "font-src 'self'",
        "object-src 'none'", "worker-src 'none'", "base-uri 'none'", "form-action 'none'",
        "frame-ancestors 'self'", "upgrade-insecure-requests"])


def draw_icon(size):
    """Gold map pin on a full-bleed navy square; pin stays inside the maskable safe zone."""
    from PIL import Image, ImageDraw
    s = size * 4  # draw large, then downsample for smooth edges
    img = Image.new("RGB", (s, s), NAVY)
    d = ImageDraw.Draw(img)
    cx, cy, r = s * 0.5, s * 0.42, s * 0.19
    tip = (cx, s * 0.80)
    d.polygon([(cx - r * 0.92, cy + r * 0.38), (cx + r * 0.92, cy + r * 0.38), tip], fill=GOLD)
    d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=GOLD)
    h = r * 0.42
    d.ellipse([cx - h, cy - h, cx + h, cy + h], fill=NAVY)
    return img.resize((size, size), Image.LANCZOS)


def main():
    SITE.mkdir(exist_ok=True)
    html = SRC.read_text(encoding="utf-8")
    # the version in Settings: when this site build ran (on Cloudflare: the deploy), not when the page was made
    sys.path.insert(0, str(ROOT / "build"))
    from stamp import build_stamp
    html = re.sub(r'(<span id="buildStamp">)[^<]*(</span>)', lambda m: m.group(1) + build_stamp() + m.group(2), html, count=1)
    if 'rel="manifest"' not in html:
        html = html.replace("</title>", "</title>\n" + HEAD_EXTRA, 1)
    # street addresses for Home / Work, road lines for "Nearest street" (both loaded by the page when needed),
    # named by their content's hash so they can be cached for a year; the page is pointed at the new names
    (SITE / "_assets").mkdir(parents=True, exist_ok=True)
    for f in (SITE / "_assets").glob("*.js"):
        f.unlink()
    for extra in ("addresses.js", "streets.js"):
        src = ROOT / "_assets" / extra
        if src.exists():
            name = extra.replace(".js", "." + hashlib.sha256(src.read_bytes()).hexdigest()[:10] + ".js")
            shutil.copy2(src, SITE / "_assets" / name)
            assert html.count(f'"_assets/{extra}"') == 1, extra
            html = html.replace(f'"_assets/{extra}"', f'"_assets/{name}"')
    (SITE / "index.html").write_text(html, encoding="utf-8")
    (SITE / "manifest.webmanifest").write_text(json.dumps(MANIFEST, ensure_ascii=False, indent=2), encoding="utf-8")
    csp = csp_for(html)
    (SITE / "_headers").write_text(HEADERS.format(csp=csp), encoding="utf-8")
    print(f"  CSP: {csp.count('sha256-')} inline scripts pinned by hash")
    try:
        for name, px in (("icon-192.png", 192), ("icon-512.png", 512), ("apple-touch-icon.png", 180)):
            draw_icon(px).save(SITE / name, optimize=True)
    except ImportError:
        for name in ("icon-192.png", "icon-512.png", "apple-touch-icon.png"):
            shutil.copy2(ROOT / "build" / "icons" / name, SITE / name)
        print("Pillow not installed: using the icons in build/icons/")
    # pronunciation clips, one mp3 per name (index.json is already embedded in the page)
    src_audio, dst_audio = ROOT / "_assets" / "audio" / "c", SITE / "_assets" / "audio" / "c"
    if dst_audio.parent.exists():
        shutil.rmtree(dst_audio.parent)
    dst_audio.mkdir(parents=True)
    for f in sorted(src_audio.glob("*.mp3")):
        shutil.copy2(f, dst_audio / f.name)
    # zip with index.html at the top level (no wrapping folder), ready for drag-and-drop upload
    zpath = ROOT / "site.zip"
    files = [f for f in sorted(SITE.rglob("*")) if f.is_file() and not f.name.startswith(".")]
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for f in files:
            z.write(f, f.relative_to(SITE).as_posix())
    for f in files:
        if f.parent == SITE:
            print(f"  site/{f.name:24s} {f.stat().st_size/1024:8.1f} KB")
    clips = [f for f in files if f.parent == dst_audio]
    if clips:
        print(f"  site/_assets/audio/c/        {len(clips)} clips, {sum(f.stat().st_size for f in clips)/1024/1024:.1f} MB")
    print(f"  site.zip {zpath.stat().st_size/1024/1024:.1f} MB, {len(files)} files")


if __name__ == "__main__":
    main()
